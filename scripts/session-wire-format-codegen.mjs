#!/usr/bin/env node

import { readFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
	checkOrWriteGeneratedTargets,
	formatRustWithRustfmt,
	formatTsWithBiome,
	rustGeneratedMatches,
} from "./codegen-utils.mjs";

const rootDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const manifestPath = resolve(rootDir, "src/session/wire-format.manifest.json");
const tsOutputPath = resolve(rootDir, "src/session/wire-format.generated.ts");
const rustOutputPath = resolve(
	rootDir,
	"packages/tui-rs/src/session/wire_format_generated.rs",
);

function isPlainObject(value) {
	return Boolean(value) && typeof value === "object" && !Array.isArray(value);
}

function assertStringMap(value, path) {
	if (!isPlainObject(value)) {
		throw new Error(`Session wire manifest ${path} must be an object`);
	}
	for (const [key, nested] of Object.entries(value)) {
		if (typeof nested !== "string") {
			throw new Error(
				`Session wire manifest ${path}.${key} must be a string`,
			);
		}
	}
}

function assertNestedStringMap(value, path) {
	if (!isPlainObject(value)) {
		throw new Error(`Session wire manifest ${path} must be an object`);
	}
	for (const [key, nested] of Object.entries(value)) {
		assertStringMap(nested, `${path}.${key}`);
	}
}

function assertStringArray(value, path) {
	if (!Array.isArray(value)) {
		throw new Error(`Session wire manifest ${path} must be an array`);
	}
	for (const [index, nested] of value.entries()) {
		if (typeof nested !== "string" || nested.length === 0) {
			throw new Error(
				`Session wire manifest ${path}[${index}] must be a non-empty string`,
			);
		}
	}
}

function validateManifest(manifest) {
	if (!isPlainObject(manifest)) {
		throw new Error("Session wire manifest must be an object");
	}
	if (typeof manifest.version !== "string" || manifest.version.length === 0) {
		throw new Error("Session wire manifest version must be a non-empty string");
	}
	assertStringMap(manifest.stopReasonAliases, "stopReasonAliases");
	assertNestedStringMap(manifest.fieldAliases, "fieldAliases");
	assertStringMap(manifest.contentBlockTypeAliases, "contentBlockTypeAliases");
	assertNestedStringMap(
		manifest.contentBlockFieldAliases,
		"contentBlockFieldAliases",
	);
	assertStringArray(
		manifest.compactionContextEntryTypes,
		"compactionContextEntryTypes",
	);
	assertStringArray(
		manifest.compactionContextExcludedMessageRoles,
		"compactionContextExcludedMessageRoles",
	);
}

function renderObject(value, indent = "") {
	if (!value || typeof value !== "object" || Array.isArray(value)) {
		return JSON.stringify(value);
	}

	const entries = Object.entries(value);
	if (entries.length === 0) {
		return "{}";
	}

	const nextIndent = `${indent}\t`;
	const rendered = entries
		.map(
			([key, nested]) =>
				`${nextIndent}${JSON.stringify(key)}: ${renderObject(nested, nextIndent)},`,
		)
		.join("\n");
	return `{\n${rendered}\n${indent}}`;
}

function renderTs(manifest) {
	return `/**
 * Auto-generated by \`scripts/session-wire-format-codegen.mjs\`.
 * Do not edit manually; update \`src/session/wire-format.manifest.json\` instead.
 */

export const sessionWireFormatVersion = ${JSON.stringify(manifest.version)} as const;

export const sessionWireStopReasonAliases = ${renderObject(manifest.stopReasonAliases)} as const;

export const sessionWireFieldAliases = ${renderObject(manifest.fieldAliases)} as const;

export const sessionWireContentBlockTypeAliases = ${renderObject(manifest.contentBlockTypeAliases)} as const;

export const sessionWireContentBlockFieldAliases = ${renderObject(manifest.contentBlockFieldAliases)} as const;

export const sessionWireCompactionContextEntryTypes = ${renderObject(manifest.compactionContextEntryTypes)} as const;

export const sessionWireCompactionContextExcludedMessageRoles = ${renderObject(manifest.compactionContextExcludedMessageRoles)} as const;

type SessionWireAliasSource = Readonly<Record<string, unknown>>;

function getSessionWireAlias<T extends SessionWireAliasSource>(
\taliases: T,
\tkey: string,
): T[keyof T] | undefined {
\treturn Object.prototype.hasOwnProperty.call(aliases, key)
\t\t? aliases[key as keyof T]
\t\t: undefined;
}

export function canonicalSessionWireStopReason(reason: string): string {
\treturn (
\t\tgetSessionWireAlias(sessionWireStopReasonAliases, reason) ?? reason
\t);
}

export function canonicalSessionWireContentBlockType(type: string): string {
\treturn (
\t\tgetSessionWireAlias(sessionWireContentBlockTypeAliases, type) ?? type
\t);
}

export function getSessionWireContentBlockFieldAliases(type: string) {
\treturn getSessionWireAlias(sessionWireContentBlockFieldAliases, type);
}

export function isSessionWireCompactionContextEntryType(type: string): boolean {
\treturn sessionWireCompactionContextEntryTypes.includes(
\t\ttype as (typeof sessionWireCompactionContextEntryTypes)[number],
\t);
}

export function isSessionWireCompactionExcludedMessageRole(
\trole: string,
): boolean {
\treturn sessionWireCompactionContextExcludedMessageRoles.includes(
\t\trole as (typeof sessionWireCompactionContextExcludedMessageRoles)[number],
\t);
}
`;
}

const RUST_MAX_WIDTH = 100;
const STOP_REASON_ALIASES_PREFIX =
	"pub const STOP_REASON_ALIASES: &[(&str, &str)] = ";
const CONTENT_BLOCK_TYPE_ALIASES_PREFIX =
	"pub const CONTENT_BLOCK_TYPE_ALIASES: &[(&str, &str)] = ";
const COMPACTION_CONTEXT_ENTRY_TYPES_PREFIX =
	"pub const COMPACTION_CONTEXT_ENTRY_TYPES: &[&str] = ";
const COMPACTION_CONTEXT_EXCLUDED_MESSAGE_ROLES_PREFIX =
	"pub const COMPACTION_CONTEXT_EXCLUDED_MESSAGE_ROLES: &[&str] = ";

function toRustArray(
	entries,
	prefixLength = 0,
	indent = "",
	forceMultiline = false,
) {
	if (entries.length === 0) {
		return "&[]";
	}
	const inline = `&[${entries
		.map(([from, to]) => `(${JSON.stringify(from)}, ${JSON.stringify(to)})`)
		.join(", ")}]`;
	if (!forceMultiline && prefixLength + inline.length + ";".length <= RUST_MAX_WIDTH) {
		return inline;
	}
	const itemIndent = `${indent}    `;
	return `&[\n${entries
		.map(
			([from, to]) =>
				`${itemIndent}(${JSON.stringify(from)}, ${JSON.stringify(to)}),`,
		)
		.join("\n")}\n${indent}]`;
}

function toRustNestedArray(entries) {
	if (entries.length === 0) {
		return "&[]";
	}
	const renderedEntries = entries.map(([section, aliases]) => {
		const aliasEntries = Object.entries(aliases ?? {});
		const aliasArray = toRustArray(
			aliasEntries,
			8,
			"        ",
			aliasEntries.length > 2,
		);
		if (aliasEntries.length <= 1 && section.length <= 16) {
			return `    (${JSON.stringify(section)}, ${aliasArray}),`;
		}
		return `    (\n        ${JSON.stringify(section)},\n        ${aliasArray},\n    ),`;
	});
	return `&[\n${renderedEntries.join("\n")}\n]`;
}

function toRustMatchArms(entries) {
	return [
		...entries.map(([key, aliases]) => {
			const aliasEntries = Object.entries(aliases ?? {});
			return `        ${JSON.stringify(key)} => ${toRustArray(
				aliasEntries,
				8,
				"        ",
				aliasEntries.length > 2,
			)},`;
		}),
		"        _ => &[],",
	].join("\n");
}

function toRustStringArray(values, prefixLength = 0) {
	if (values.length === 0) {
		return "&[]";
	}
	const inline = `&[${values.map((value) => JSON.stringify(value)).join(", ")}]`;
	if (prefixLength + inline.length + ";".length <= RUST_MAX_WIDTH) {
		return inline;
	}
	return `&[\n${values
		.map((value) => `    ${JSON.stringify(value)},`)
		.join("\n")}\n]`;
}

function toRustStringMatcher(functionName, argumentName, values) {
	if (values.length === 0) {
		return `#[must_use]
pub fn ${functionName}(_${argumentName}: &str) -> bool {
    false
}`;
	}
	const pattern = values
		.map((value) => `        ${JSON.stringify(value)}`)
		.join("\n        | ");
	return `#[must_use]
pub fn ${functionName}(${argumentName}: &str) -> bool {
    matches!(
        ${argumentName},
${pattern}
    )
}`;
}

function renderRust(manifest) {
	const stopAliases = Object.entries(manifest.stopReasonAliases ?? {});
	const contentBlockTypeAliases = Object.entries(
		manifest.contentBlockTypeAliases ?? {},
	);
	const contentBlockFieldAliases = Object.entries(
		manifest.contentBlockFieldAliases ?? {},
	);
	const fieldAliases = Object.entries(manifest.fieldAliases ?? {});
	const compactionContextEntryTypes =
		manifest.compactionContextEntryTypes ?? [];
	const compactionContextExcludedMessageRoles =
		manifest.compactionContextExcludedMessageRoles ?? [];
	const stopReasonMatchArms = [
		...stopAliases.map(
			([from, to]) => `        ${JSON.stringify(from)} => ${JSON.stringify(to)},`,
		),
		"        other => other,",
	].join("\n");
	const contentBlockTypeMatchArms = [
		...contentBlockTypeAliases.map(
			([from, to]) => `        ${JSON.stringify(from)} => ${JSON.stringify(to)},`,
		),
		"        other => other,",
	].join("\n");

	return `// Auto-generated by \`scripts/session-wire-format-codegen.mjs\`.
// Do not edit manually; update \`src/session/wire-format.manifest.json\` instead.
#![allow(dead_code)]

pub const SESSION_WIRE_FORMAT_VERSION: &str = ${JSON.stringify(manifest.version)};

${STOP_REASON_ALIASES_PREFIX}${toRustArray(stopAliases, STOP_REASON_ALIASES_PREFIX.length)};

${CONTENT_BLOCK_TYPE_ALIASES_PREFIX}${toRustArray(contentBlockTypeAliases, CONTENT_BLOCK_TYPE_ALIASES_PREFIX.length)};

pub const CONTENT_BLOCK_FIELD_ALIASES: &[(&str, &[(&str, &str)])] = ${toRustNestedArray(
		contentBlockFieldAliases,
	)};

pub const FIELD_ALIASES: &[(&str, &[(&str, &str)])] = ${toRustNestedArray(fieldAliases)};

${COMPACTION_CONTEXT_ENTRY_TYPES_PREFIX}${toRustStringArray(
		compactionContextEntryTypes,
		COMPACTION_CONTEXT_ENTRY_TYPES_PREFIX.length,
	)};

${COMPACTION_CONTEXT_EXCLUDED_MESSAGE_ROLES_PREFIX}${toRustStringArray(
		compactionContextExcludedMessageRoles,
		COMPACTION_CONTEXT_EXCLUDED_MESSAGE_ROLES_PREFIX.length,
	)};

#[must_use]
pub fn canonical_stop_reason(reason: &str) -> &str {
    match reason {
${stopReasonMatchArms}
    }
}

#[must_use]
pub fn canonical_content_block_type(block_type: &str) -> &str {
    match block_type {
${contentBlockTypeMatchArms}
    }
}

#[must_use]
pub fn content_block_field_aliases(block_type: &str) -> &'static [(&'static str, &'static str)] {
    match block_type {
${toRustMatchArms(contentBlockFieldAliases)}
    }
}

#[must_use]
pub fn field_aliases(section: &str) -> &'static [(&'static str, &'static str)] {
	match section {
${toRustMatchArms(fieldAliases)}
    }
}

${toRustStringMatcher("is_compaction_context_entry_type", "entry_type", compactionContextEntryTypes)}

${toRustStringMatcher("is_compaction_context_excluded_message_role", "role", compactionContextExcludedMessageRoles)}
`;
}

async function main() {
	const check = process.argv.includes("--check");
	const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
	validateManifest(manifest);
	const rustSource = renderRust(manifest);
	const rustOutput = formatRustWithRustfmt(rustSource, rustOutputPath, {
		rootDir,
		label: "generated Rust session wire file",
		check,
		envNames: ["SESSION_WIRE_FORMAT_RUSTFMT"],
		tempPrefix: ".session-wire-codegen-",
	});
	const targets = [
		{
			path: tsOutputPath,
			content: formatTsWithBiome(renderTs(manifest), tsOutputPath, {
				rootDir,
				label: "generated TypeScript session wire file",
				tempPrefix: ".session-wire-codegen-",
			}),
			matches: (current, expected) => current === expected,
		},
		{
			path: rustOutputPath,
			content: rustOutput.content,
			matches: (current, expected) =>
				rustGeneratedMatches(current, expected, {
					rustfmtAvailable: rustOutput.rustfmtAvailable,
				}),
		},
	];

	await checkOrWriteGeneratedTargets(targets, {
		check,
		outOfDateLabel: "Session wire generated file is out of date",
	});
}

await main();
