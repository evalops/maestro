#!/usr/bin/env node

import { spawnSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const rootDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const manifestPath = resolve(rootDir, "src/session/wire-format.manifest.json");
const tsOutputPath = resolve(rootDir, "src/session/wire-format.generated.ts");
const rustOutputPath = resolve(
	rootDir,
	"packages/tui-rs/src/session/wire_format_generated.rs",
);

function isPlainObject(value) {
	return Boolean(value) && typeof value === "object" && !Array.isArray(value);
}

function assertStringMap(value, path) {
	if (!isPlainObject(value)) {
		throw new Error(`Session wire manifest ${path} must be an object`);
	}
	for (const [key, nested] of Object.entries(value)) {
		if (typeof nested !== "string") {
			throw new Error(
				`Session wire manifest ${path}.${key} must be a string`,
			);
		}
	}
}

function assertNestedStringMap(value, path) {
	if (!isPlainObject(value)) {
		throw new Error(`Session wire manifest ${path} must be an object`);
	}
	for (const [key, nested] of Object.entries(value)) {
		assertStringMap(nested, `${path}.${key}`);
	}
}

function validateManifest(manifest) {
	if (!isPlainObject(manifest)) {
		throw new Error("Session wire manifest must be an object");
	}
	if (typeof manifest.version !== "string" || manifest.version.length === 0) {
		throw new Error("Session wire manifest version must be a non-empty string");
	}
	assertStringMap(manifest.stopReasonAliases, "stopReasonAliases");
	assertNestedStringMap(manifest.fieldAliases, "fieldAliases");
	assertStringMap(manifest.contentBlockTypeAliases, "contentBlockTypeAliases");
	assertNestedStringMap(
		manifest.contentBlockFieldAliases,
		"contentBlockFieldAliases",
	);
}

function renderObject(value, indent = "") {
	if (!value || typeof value !== "object" || Array.isArray(value)) {
		return JSON.stringify(value);
	}

	const entries = Object.entries(value);
	if (entries.length === 0) {
		return "{}";
	}

	const nextIndent = `${indent}\t`;
	const rendered = entries
		.map(
			([key, nested]) =>
				`${nextIndent}${JSON.stringify(key)}: ${renderObject(nested, nextIndent)},`,
		)
		.join("\n");
	return `{\n${rendered}\n${indent}}`;
}

function renderTs(manifest) {
	return `/**
 * Auto-generated by \`scripts/session-wire-format-codegen.mjs\`.
 * Do not edit manually; update \`src/session/wire-format.manifest.json\` instead.
 */

export const sessionWireFormatVersion = ${JSON.stringify(manifest.version)} as const;

export const sessionWireStopReasonAliases = ${renderObject(manifest.stopReasonAliases)} as const;

export const sessionWireFieldAliases = ${renderObject(manifest.fieldAliases)} as const;

export const sessionWireContentBlockTypeAliases = ${renderObject(manifest.contentBlockTypeAliases)} as const;

export const sessionWireContentBlockFieldAliases = ${renderObject(manifest.contentBlockFieldAliases)} as const;

type SessionWireAliasSource = Readonly<Record<string, unknown>>;

function getSessionWireAlias<T extends SessionWireAliasSource>(
\taliases: T,
\tkey: string,
): T[keyof T] | undefined {
\treturn Object.prototype.hasOwnProperty.call(aliases, key)
\t\t? aliases[key as keyof T]
\t\t: undefined;
}

export function canonicalSessionWireStopReason(reason: string): string {
\treturn (
\t\tgetSessionWireAlias(sessionWireStopReasonAliases, reason) ?? reason
\t);
}

export function canonicalSessionWireContentBlockType(type: string): string {
\treturn (
\t\tgetSessionWireAlias(sessionWireContentBlockTypeAliases, type) ?? type
\t);
}

export function getSessionWireContentBlockFieldAliases(type: string) {
\treturn getSessionWireAlias(sessionWireContentBlockFieldAliases, type);
}
`;
}

const RUST_MAX_WIDTH = 100;
const STOP_REASON_ALIASES_PREFIX =
	"pub const STOP_REASON_ALIASES: &[(&str, &str)] = ";

function toRustArray(entries, prefixLength = 0) {
	if (entries.length === 0) {
		return "&[]";
	}
	const inline = `&[${entries
		.map(([from, to]) => `(${JSON.stringify(from)}, ${JSON.stringify(to)})`)
		.join(", ")}]`;
	if (prefixLength + inline.length + ";".length <= RUST_MAX_WIDTH) {
		return inline;
	}
	return `&[\n${entries
		.map(([from, to]) => `    (${JSON.stringify(from)}, ${JSON.stringify(to)}),`)
		.join("\n")}\n]`;
}

function renderRust(manifest) {
	const stopAliases = Object.entries(manifest.stopReasonAliases ?? {});
	const matchArms = [
		...stopAliases.map(
			([from, to]) => `        ${JSON.stringify(from)} => ${JSON.stringify(to)},`,
		),
		"        other => other,",
	].join("\n");

	return `// Auto-generated by \`scripts/session-wire-format-codegen.mjs\`.
// Do not edit manually; update \`src/session/wire-format.manifest.json\` instead.
#![allow(dead_code)]

pub const SESSION_WIRE_FORMAT_VERSION: &str = ${JSON.stringify(manifest.version)};

${STOP_REASON_ALIASES_PREFIX}${toRustArray(stopAliases, STOP_REASON_ALIASES_PREFIX.length)};

#[must_use]
pub fn canonical_stop_reason(reason: &str) -> &str {
    match reason {
${matchArms}
    }
}
`;
}

function formatTs(source, outputPath) {
	const tempDir = mkdtempSync(join(dirname(outputPath), ".session-wire-codegen-"));
	const tempPath = join(tempDir, "wire-format.generated.ts");
	try {
		writeFileSync(tempPath, source, "utf8");
		const result = spawnSync(
			"bunx",
			["biome", "check", "--write", "--unsafe", tempPath],
			{
				cwd: rootDir,
				encoding: "utf8",
			},
		);
		if (result.status !== 0) {
			throw new Error(
				`Failed to format generated TypeScript session wire file: ${result.stderr || result.stdout}`,
			);
		}
		return readFileSync(tempPath, "utf8");
	} finally {
		rmSync(tempDir, { recursive: true, force: true });
	}
}

async function main() {
	const check = process.argv.includes("--check");
	const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
	validateManifest(manifest);
	const rustSource = renderRust(manifest);
	const targets = [
		{
			path: tsOutputPath,
			content: formatTs(renderTs(manifest), tsOutputPath),
		},
		{
			path: rustOutputPath,
			content: rustSource,
		},
	];

	if (check) {
		let failed = false;
		for (const target of targets) {
			const current = await readFile(target.path, "utf8").catch(() => null);
			if (current !== target.content) {
				failed = true;
				console.error(
					`Session wire generated file is out of date: ${target.path}`,
				);
			}
		}
		if (failed) {
			process.exitCode = 1;
		}
		return;
	}

	for (const target of targets) {
		await mkdir(dirname(target.path), { recursive: true });
		await writeFile(target.path, target.content);
	}
}

await main();
